#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const DRAFT_2020_12 = "https://json-schema.org/draft/2020-12/schema";
const SCHEMA_PREFIX = "urn:lifecycle:schema:";
const schemasRoot = resolve(import.meta.dirname, "..", "..", "spec-source", "schemas");
const publicationManifestPath = resolve(import.meta.dirname, "..", "..", "spec-source", "publication-manifest.json");
const outputPath = resolve(import.meta.dirname, "..", "src", "foundation", "validation", "generated-schemas.ts");

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
}

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function digest(bytes) {
  return `sha256:${createHash("sha256").update(bytes).digest("hex")}`;
}

function schemaSetDigest(entries) {
  return digest(Buffer.from(JSON.stringify(entries.map(({ path, id, sourceDigest }) => ({ path, id, sourceDigest }))), "utf8"));
}

async function schemaEntries() {
  const directoryEntries = await readdir(schemasRoot, { withFileTypes: true });
  const names = directoryEntries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".schema.json"))
    .map((entry) => entry.name)
    .sort(compareText);
  if (names.length === 0) throw new Error(`No Draft 2020-12 schemas were found beneath ${schemasRoot}`);

  const ids = new Map();
  const entries = [];
  for (const name of names) {
    const path = resolve(schemasRoot, name);
    const bytes = await readFile(path);
    if (bytes.length >= 3 && bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) {
      throw new Error(`${name} contains a forbidden UTF-8 byte-order mark`);
    }
    if (bytes.includes(0)) throw new Error(`${name} contains a forbidden NUL byte`);
    const source = bytes.toString("utf8");
    if (!Buffer.from(source, "utf8").equals(bytes)) throw new Error(`${name} is not well-formed UTF-8`);
    let schema;
    try {
      schema = JSON.parse(source);
    } catch (error) {
      throw new Error(`${name} is not valid JSON: ${error instanceof Error ? error.message : String(error)}`);
    }
    if (schema === null || typeof schema !== "object" || Array.isArray(schema)) {
      throw new Error(`${name} must contain one JSON object`);
    }
    if (schema.$schema !== DRAFT_2020_12) {
      throw new Error(`${name} must select ${DRAFT_2020_12}`);
    }
    if (typeof schema.$id !== "string" || !schema.$id.startsWith(SCHEMA_PREFIX)) {
      throw new Error(`${name} must declare one ${SCHEMA_PREFIX} identifier`);
    }
    const earlier = ids.get(schema.$id);
    if (earlier !== undefined) throw new Error(`${name} duplicates schema id ${schema.$id} from ${earlier}`);
    ids.set(schema.$id, name);
    entries.push({ path: `spec-source/schemas/${name}`, id: schema.$id, sourceDigest: digest(bytes), schema });
  }
  return entries;
}

async function publicationIdentity() {
  const value = JSON.parse(await readFile(publicationManifestPath, "utf8"));
  if (typeof value.specificationRevision !== "string" || value.specificationRevision.length === 0) {
    throw new Error("Publication manifest lacks one specification revision");
  }
  if (typeof value.publicationDigest !== "string" || !/^sha256:[a-f0-9]{64}$/u.test(value.publicationDigest)) {
    throw new Error("Publication manifest lacks one lowercase SHA-256 publication digest");
  }
  return { revision: value.specificationRevision, digest: value.publicationDigest };
}

function generatedSource(entries, publication) {
  const serializedEntries = entries.map((entry) => [
    "  {",
    `    path: ${JSON.stringify(entry.path)},`,
    `    id: ${JSON.stringify(entry.id)},`,
    `    sourceDigest: ${JSON.stringify(entry.sourceDigest)},`,
    `    schema: ${JSON.stringify(entry.schema, null, 2).replaceAll("\n", "\n    ")},`,
    "  },",
  ].join("\n")).join("\n");
  return [
    "// Generated by runtime/scripts/generate-foundation-schemas.mjs.",
    "// Do not edit this checked source carrier directly.",
    "",
    "export type GeneratedFoundationSchema = Readonly<{",
    "  path: string;",
    "  id: string;",
    "  sourceDigest: `sha256:${string}`;",
    "  schema: Record<string, unknown>;",
    "}>;",
    "",
    "function deepFreeze<T>(value: T, seen = new Set<object>()): T {",
    "  if (value === null || typeof value !== \"object\" || seen.has(value)) return value;",
    "  seen.add(value);",
    "  for (const child of Object.values(value as Record<string, unknown>)) deepFreeze(child, seen);",
    "  return Object.freeze(value);",
    "}",
    "",
    `export const FOUNDATION_GENERATED_SPECIFICATION_REVISION = ${JSON.stringify(publication.revision)} as const;`,
    `export const FOUNDATION_GENERATED_PUBLICATION_DIGEST = ${JSON.stringify(publication.digest)} as const;`,
    `export const FOUNDATION_GENERATED_SCHEMA_SET_DIGEST = ${JSON.stringify(schemaSetDigest(entries))} as const;`,
    "",
    "export const FOUNDATION_GENERATED_SCHEMAS: readonly GeneratedFoundationSchema[] = deepFreeze([",
    serializedEntries,
    "]);",
    "",
  ].join("\n");
}

async function main() {
  const check = process.argv.length === 3 && process.argv[2] === "--check";
  if (!check && process.argv.length !== 2) {
    fail("Usage: node runtime/scripts/generate-foundation-schemas.mjs [--check]");
    return;
  }
  const [entries, publication] = await Promise.all([schemaEntries(), publicationIdentity()]);
  const expected = generatedSource(entries, publication);
  if (check) {
    let observed;
    try {
      observed = await readFile(outputPath, "utf8");
    } catch (error) {
      if (error && typeof error === "object" && error.code === "ENOENT") {
        fail("Generated foundation schema carrier is missing; run the generator without --check");
        return;
      }
      throw error;
    }
    if (observed !== expected) {
      fail("Generated foundation schema carrier is stale; run the generator without --check");
    }
    return;
  }
  await writeFile(outputPath, expected, "utf8");
}

await main();
